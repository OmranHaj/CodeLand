// Bundles the games' verifier (frontend/src/games/verify/judgeEntry.js and the three game engines)
// into one CommonJS program and saves it as a string in src/games/game-verifier.source.ts, which the
// server sends to Judge0. Run `npm run build:game-verifier` after changing a game engine.
import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { rolldown } from 'rolldown';

const here = dirname(fileURLToPath(import.meta.url));
const entry = resolve(here, '../../frontend/src/games/verify/judgeEntry.js');
const target = resolve(here, '../src/games/game-verifier.source.ts');

const bundle = await rolldown({ input: entry, platform: 'node', logLevel: 'warn' });
const { output } = await bundle.generate({ format: 'cjs' });
await bundle.close();

const source = output[0].code;
await writeFile(
  target,
  `// Generated by scripts/build-game-verifier.mjs from frontend/src/games/verify. Do not edit by hand.\n` +
    `export const GAME_VERIFIER_SOURCE: string = ${JSON.stringify(source)};\n`,
);
console.log(`Wrote ${target} (${(source.length / 1024).toFixed(1)} KB)`);
